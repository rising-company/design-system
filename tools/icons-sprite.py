# Usage: npm pack lucide-static && tar xzf lucide-static-*.tgz
#        python3 tools/icons-sprite.py package/
# Regenerates branding/icons.svg, the sprite of the Lucide icons the system uses.
# Each shape keeps only its geometry: stroke, fill, caps and joins come from
# .icon in rising.css, so the squared ends and 1.5px stroke live in one place.
# vector-effect keeps the stroke 1.5px at 16, 20 and 24 (Lucide's absoluteStrokeWidth).
import json, pathlib, re, sys
import xml.etree.ElementTree as ET

NAMES = [
    "arrow-left", "arrow-right", "arrow-up", "arrow-down", "arrow-up-right", "arrow-up-down",
    "chevron-down", "chevron-right", "plus", "minus", "check", "x", "menu", "search",
    "info", "circle-check", "circle-alert", "triangle-alert",
    "external-link", "copy", "settings", "user", "log-out",
]
GEOMETRY = {"d", "x", "y", "x1", "y1", "x2", "y2", "cx", "cy", "r", "rx", "ry", "width", "height", "points"}
SVG = "{http://www.w3.org/2000/svg}"

pkg = pathlib.Path(sys.argv[1])
version = json.loads((pkg / "package.json").read_text())["version"]
out = [f'<svg xmlns="http://www.w3.org/2000/svg">',
       f'<!-- Lucide v{version} (ISC, lucide.dev), restyled by .icon in rising.css. Generated by tools/icons-sprite.py. -->']
for name in NAMES:
    root = ET.fromstring(re.sub(r"<!--.*?-->", "", (pkg / "icons" / f"{name}.svg").read_text(), flags=re.S))
    shapes = []
    for el in root:
        tag = el.tag.replace(SVG, "")
        attrs = "".join(f' {k}="{v}"' for k, v in el.attrib.items() if k in GEOMETRY)
        shapes.append(f"<{tag}{attrs} vector-effect=\"non-scaling-stroke\"/>")
    out.append(f'<symbol id="{name}" viewBox="0 0 24 24">{"".join(shapes)}</symbol>')
out.append("</svg>\n")
(pathlib.Path(__file__).resolve().parent.parent / "branding" / "icons.svg").write_text("\n".join(out))
print(f"branding/icons.svg: {len(NAMES)} icons from Lucide v{version}")
